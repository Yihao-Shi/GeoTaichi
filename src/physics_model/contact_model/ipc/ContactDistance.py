@ti.func
def solve_ldlt_2d(A00, A01, A11, b0, b1):
    D00 = A00
    L01 = A01 / D00
    D11 = A11 - L01 * L01 * D00
    y0 = b0
    y1 = b1 - L01 * y0
    x1 = y1 / D11
    x0 = (y0 - D00 * L01 * x1) / D00
    return x0, x1


@ti.func
def point_edge_distance_type(p, e0, e1):
    edge = e1 - e0
    edge_length2 = edge.dot(edge)
    dtype = 2
    if edge_length2 == 0.0:
        dtype = 0
    else:
        ratio = edge.dot(p - e0) / edge_length2
        if ratio < 0.0:
            dtype = 0
        elif ratio > 1.0:
            dtype = 1
    return dtype


@ti.func
def point_edge_distance2(p, e0, e1):
    """Squared distance from a 2D/3D point to a finite segment."""
    dtype = point_edge_distance_type(p, e0, e1)
    distance2 = 0.0
    if dtype == 0:
        distance2 = point_point_distance2(p, e0)
    elif dtype == 1:
        distance2 = point_point_distance2(p, e1)
    else:
        if ti.static(p.n == 2):
            edge = e1 - e0
            offset = p - e0
            cross = edge[0] * offset[1] - edge[1] * offset[0]
            distance2 = cross * cross / ti.max(edge.dot(edge), 1.0e-30)
        else:
            distance2 = point_line_distance2(p, e0, e1)
    return distance2


@ti.func
def point_edge_distance_grad_hess_2d(p, e0, e1):
    """Exact 2D point--segment squared-distance derivatives.

    The output ordering is ``(p, e0, e1)`` with two coordinates per site.
    Endpoint regions reduce to point--point distance.  The interior region
    reuses the generated analytic point--line expressions and extracts their
    in-plane entries; no finite differences or autodiff tapes are involved.
    """
    dtype = point_edge_distance_type(p, e0, e1)
    gradient = ti.Vector.zero(float, 6)
    hessian = ti.Matrix.zero(float, 6, 6)
    distance2 = 0.0
    if dtype == 0 or dtype == 1:
        endpoint = e0
        endpoint_site = 1
        if dtype == 1:
            endpoint = e1
            endpoint_site = 2
        delta = p - endpoint
        distance2 = delta.dot(delta)
        for component in ti.static(range(2)):
            gradient[component] = 2.0 * delta[component]
            gradient[2 * endpoint_site + component] = -2.0 * delta[component]
            hessian[component, component] = 2.0
            hessian[2 * endpoint_site + component, 2 * endpoint_site + component] = 2.0
            hessian[component, 2 * endpoint_site + component] = -2.0
            hessian[2 * endpoint_site + component, component] = -2.0
    else:
        p3 = ti.Vector([p[0], p[1], 0.0])
        e03 = ti.Vector([e0[0], e0[1], 0.0])
        e13 = ti.Vector([e1[0], e1[1], 0.0])
        distance2 = point_line_distance2(p3, e03, e13)
        gradient3 = g_PE3D(p3, e03, e13)
        hessian3 = H_PE3D(p3, e03, e13)
        for site, component in ti.static(ti.ndrange(3, 2)):
            gradient[2 * site + component] = gradient3[3 * site + component]
        for first, second in ti.static(ti.ndrange(3, 3)):
            for row, column in ti.static(ti.ndrange(2, 2)):
                hessian[2 * first + row, 2 * second + column] = hessian3[3 * first + row, 3 * second + column]
    return distance2, gradient, hessian, dtype


@ti.func
def point_triangle_distance_type(p, t0, t1, t2):
    basis_row0 = t1 - t0
    basis_row1 = t2 - t0
    nvec = basis_row0.cross(basis_row1)
    basis_row1 = basis_row0.cross(nvec)
    sys00 = basis_row0.dot(basis_row0)
    sys01 = basis_row0.dot(basis_row1)
    sys11 = basis_row1.dot(basis_row1)
    b = p - t0
    rhs0 = basis_row0.dot(b)
    rhs1 = basis_row1.dot(b)
    param0_0, param0_1 = solve_ldlt_2d(sys00, sys01, sys11, rhs0, rhs1)
    dtype = 6
    if param0_0 > 0.0 and param0_0 < 1.0 and param0_1 >= 0.0:
        dtype = 3
    else:
        basis_row0 = t2 - t1
        basis_row1 = basis_row0.cross(nvec)
        sys00 = basis_row0.dot(basis_row0)
        sys01 = basis_row0.dot(basis_row1)
        sys11 = basis_row1.dot(basis_row1)
        b = p - t1
        rhs0 = basis_row0.dot(b)
        rhs1 = basis_row1.dot(b)
        param1_0, param1_1 = solve_ldlt_2d(sys00, sys01, sys11, rhs0, rhs1)
        if param1_0 > 0.0 and param1_0 < 1.0 and param1_1 >= 0.0:
            dtype = 4
        else:
            basis_row0 = t0 - t2
            basis_row1 = basis_row0.cross(nvec)
            sys00 = basis_row0.dot(basis_row0)
            sys01 = basis_row0.dot(basis_row1)
            sys11 = basis_row1.dot(basis_row1)
            b = p - t2
            rhs0 = basis_row0.dot(b)
            rhs1 = basis_row1.dot(b)
            param2_0, param2_1 = solve_ldlt_2d(sys00, sys01, sys11, rhs0, rhs1)
            if param2_0 > 0.0 and param2_0 < 1.0 and param2_1 >= 0.0:
                dtype = 5
            else:
                if param0_0 <= 0.0 and param2_0 >= 1.0:
                    dtype = 0
                elif param1_0 <= 0.0 and param0_0 >= 1.0:
                    dtype = 1
                elif param2_0 <= 0.0 and param1_0 >= 1.0:
                    dtype = 2
                else:
                    dtype = 6
    return dtype


