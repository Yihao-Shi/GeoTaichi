@ti.func
def point_point_grad_hess(a, b):
    g = ti.Vector.zero(float, 6)
    H = ti.Matrix.zero(float, 6, 6)
    for d in range(3):
        g[d] = 2.0 * (a[d] - b[d])
        g[d + 3] = -g[d]
        H[d, d] = 2.0
        H[d + 3, d + 3] = 2.0
        H[d, d + 3] = -2.0
        H[d + 3, d] = -2.0
    return g, H


@ti.func
def point_point_grad(a, b):
    g = ti.Vector.zero(float, 6)
    for d in range(3):
        g[d] = 2.0 * (a[d] - b[d])
        g[d + 3] = -g[d]
    return g


@ti.func
def point_point_distance2(a, b):
    delta = a - b
    return delta.dot(delta)


@ti.func
def point_line_distance2(p, e0, e1):
    e = e1 - e0
    cross = (p - e0).cross(p - e1)
    return cross.dot(cross) / ti.max(e.dot(e), 1.0e-30)


@ti.func
def point_plane_distance2(p, t0, t1, t2):
    normal = (t1 - t0).cross(t2 - t0)
    numerator = (p - t0).dot(normal)
    return numerator * numerator / ti.max(normal.dot(normal), 1.0e-30)


@ti.func
def line_line_distance2(ea0, ea1, eb0, eb1):
    u = ea1 - ea0
    v = eb1 - eb0
    w = ea0 - eb0
    n = u.cross(v)
    return ti.pow(w.dot(n), 2.0) / ti.max(n.dot(n), 1.0e-30)


